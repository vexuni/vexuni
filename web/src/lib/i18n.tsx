const dicts: Record<Locale, Record<string, string>> = { "zh-CN": zh, en };

function detect(): Locale {
  const stored =
    localStorage.getItem("vexuni.locale") ||
    document.cookie.match(/vexuni_locale=(zh-CN|en)/)?.[1];
  if (stored === "en" || stored === "zh-CN") return stored;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

interface I18n {
  locale: Locale;
  t: (key: string) => string;
  setLocale: (l: Locale) => void;
}

const I18nContext = createContext<I18n>({
  locale: "zh-CN",
  t: (k) => zh[k] ?? k,
  setLocale: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detect);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem("vexuni.locale", l);
    document.cookie = `vexuni_locale=${l};path=/;max-age=31536000;SameSite=Strict`;
  }, []);
  const t = useCallback((key: string) => dicts[locale][key] ?? zh[key] ?? key, [locale]);
  const value = useMemo(() => ({ locale, t, setLocale }), [locale, t, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}
